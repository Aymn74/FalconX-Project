"""
Report generation engine for PharmIntel.
"""
import logging
from datetime import date, datetime
from typing import Dict, List, Optional, Any
from pathlib import Path
import json

from jinja2 import Environment, FileSystemLoader, Template
from reportlab.lib.pagesizes import letter, A4
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, PageBreak
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import inch
from reportlab.lib import colors

from pharmintel.config import REPORTS_DIR, REPORT_COMPANY_NAME

logger = logging.getLogger(__name__)


class ReportGenerator:
    """Generates various reports in different formats."""

    def __init__(self, output_dir: Optional[Path] = None):
        """
        Initialize report generator.

        Args:
            output_dir: Directory for report output (default: config REPORTS_DIR)
        """
        self.output_dir = Path(output_dir) if output_dir else REPORTS_DIR
        self.output_dir.mkdir(parents=True, exist_ok=True)

        # Initialize Jinja2 for templates
        template_dir = Path(__file__).parent / "templates"
        template_dir.mkdir(exist_ok=True)
        self.jinja_env = Environment(loader=FileSystemLoader(str(template_dir)))

        logger.info(f"Report generator initialized. Output: {self.output_dir}")

    def generate_json_report(
        self,
        report_data: Dict,
        filename: str
    ) -> Path:
        """
        Generate JSON report.

        Args:
            report_data: Report data dictionary
            filename: Output filename

        Returns:
            Path to generated report
        """
        output_path = self.output_dir / filename

        with open(output_path, 'w', encoding='utf-8') as f:
            json.dump(report_data, f, indent=2, default=str)

        logger.info(f"Generated JSON report: {output_path}")
        return output_path

    def generate_html_report(
        self,
        report_data: Dict,
        template_name: str,
        filename: str
    ) -> Path:
        """
        Generate HTML report using Jinja2 template.

        Args:
            report_data: Report data dictionary
            template_name: Name of Jinja2 template
            filename: Output filename

        Returns:
            Path to generated report
        """
        try:
            template = self.jinja_env.get_template(template_name)
        except:
            # If template doesn't exist, use default
            template = self._get_default_html_template()

        html_content = template.render(
            report_data=report_data,
            generated_date=date.today().strftime("%Y-%m-%d"),
            company_name=REPORT_COMPANY_NAME
        )

        output_path = self.output_dir / filename

        with open(output_path, 'w', encoding='utf-8') as f:
            f.write(html_content)

        logger.info(f"Generated HTML report: {output_path}")
        return output_path

    def _get_default_html_template(self) -> Template:
        """Get default HTML template."""
        html_template = """
<!DOCTYPE html>
<html>
<head>
    <title>{{ report_data.get('title', 'PharmIntel Report') }}</title>
    <style>
        body { font-family: Arial, sans-serif; margin: 40px; }
        h1 { color: #2c3e50; }
        h2 { color: #34495e; margin-top: 30px; }
        table { border-collapse: collapse; width: 100%; margin: 20px 0; }
        th, td { border: 1px solid #ddd; padding: 12px; text-align: left; }
        th { background-color: #3498db; color: white; }
        tr:nth-child(even) { background-color: #f2f2f2; }
        .summary { background-color: #ecf0f1; padding: 20px; border-radius: 5px; margin: 20px 0; }
        .footer { margin-top: 40px; text-align: center; color: #7f8c8d; }
    </style>
</head>
<body>
    <h1>{{ report_data.get('title', 'PharmIntel Report') }}</h1>
    <div class="summary">
        <p><strong>Generated:</strong> {{ generated_date }}</p>
        <p><strong>Organization:</strong> {{ company_name }}</p>
    </div>

    <pre>{{ report_data | tojson(indent=2) }}</pre>

    <div class="footer">
        <p>Generated by {{ company_name }} PharmIntel System</p>
    </div>
</body>
</html>
"""
        return Template(html_template)

    def generate_gap_analysis_report(
        self,
        gap_data: Dict,
        format: str = "json"
    ) -> Path:
        """Generate gap analysis report."""
        timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        filename = f"gap_analysis_{timestamp}.{format}"

        if format == "json":
            return self.generate_json_report(gap_data, filename)
        elif format == "html":
            return self.generate_html_report(gap_data, "gap_analysis.html", filename)
        else:
            raise ValueError(f"Unsupported format: {format}")

