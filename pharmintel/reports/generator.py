    def generate_executive_summary(
        self,
        all_data: Dict,
        format: str = "json"
    ) -> Path:
        """
        Generate executive summary combining all analyses.

        Args:
            all_data: Dictionary containing all report data
            format: Output format

        Returns:
            Path to generated report
        """
        timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        filename = f"executive_summary_{timestamp}.{format}"

        executive_data = {
            "title": "PharmIntel Executive Summary",
            "generated_date": date.today().isoformat(),
            "summary": {
                "gap_analysis": all_data.get("gap_analysis", {}).get("summary", {}),
                "expiry_tracking": all_data.get("expiry", {}).get("summary", {}),
                "inventory": all_data.get("inventory", {}).get("summary", {}),
                "lending": all_data.get("lending", {}).get("summary", {}),
                "non_formulary": all_data.get("non_formulary", {}).get("summary", {})
            },
            "key_findings": self._extract_key_findings(all_data),
            "recommendations": self._extract_all_recommendations(all_data)
        }

        if format == "json":
            return self.generate_json_report(executive_data, filename)
        elif format == "html":
            return self.generate_html_report(executive_data, "executive_summary.html", filename)
        else:
            raise ValueError(f"Unsupported format: {format}")

    def _extract_key_findings(self, all_data: Dict) -> List[str]:
        """Extract key findings from all reports."""
        findings = []

        # Gap analysis
        gap_data = all_data.get("gap_analysis", {})
        if gap_data.get("summary", {}).get("critical_gaps", 0) > 0:
            findings.append(
                f"Critical gaps identified: {gap_data['summary']['critical_gaps']} therapeutic areas"
            )

        # Expiry
        expiry_data = all_data.get("expiry", {})
        if expiry_data.get("summary", {}).get("critical_alerts", 0) > 0:
            findings.append(
                f"Critical expiry alerts: {expiry_data['summary']['critical_alerts']} batches"
            )

        # Inventory
        inventory_data = all_data.get("inventory", {})
        if inventory_data.get("summary", {}).get("critical_alerts", 0) > 0:
            findings.append(
                f"Critical stock alerts: {inventory_data['summary']['critical_alerts']} items"
            )

        return findings

    def _extract_all_recommendations(self, all_data: Dict) -> List[str]:
        """Extract all recommendations from reports."""
        recommendations = []

        for report_type in ["gap_analysis", "expiry", "inventory", "lending", "non_formulary"]:
            report_data = all_data.get(report_type, {})
            recs = report_data.get("recommendations", [])
            recommendations.extend(recs)

        return recommendations
